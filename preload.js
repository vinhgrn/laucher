const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('electronAPI', {
    beginLaunch: (info) => ipcRenderer.invoke('begin-launch', info),
    finishLaunch: (hwnd) => ipcRenderer.invoke('finish-launch', hwnd),
    launchWindowInfo: (hwnd) => ipcRenderer.invoke('launch-window-info', hwnd),
    getDisplayBounds: () => ipcRenderer.invoke('display-bounds'),
    getControls: () => ipcRenderer.invoke('get-controls'),
    setControl: (params) => ipcRenderer.invoke('set-control', params),
    onMemoryPressure: (cb) => {
        const listener = (_, value) => cb(value);
        ipcRenderer.on('memory-pressure', listener);
        return () => ipcRenderer.removeListener('memory-pressure', listener);
    },
    getApps: () => ipcRenderer.invoke('get-apps'),
    rescanApps: () => ipcRenderer.invoke('rescan-apps'),
    getWindows: () => ipcRenderer.invoke('get-windows'),
    getWindowPreviews: () => ipcRenderer.invoke('get-window-previews'),
    setLauncherView: (view) => ipcRenderer.invoke('set-launcher-view', view),
    captureWindow: (hwnd, path) => ipcRenderer.invoke('capture-window', { hwnd, path }),
    minimizeWindow: (hwnd) => ipcRenderer.invoke('minimize-window', hwnd),
    restoreWindow: (hwnd) => ipcRenderer.invoke('restore-window', hwnd),
    maximizeWindow: (hwnd) => ipcRenderer.invoke('maximize-window', hwnd),
    closeWindow: (hwnd) => ipcRenderer.invoke('close-window', hwnd),
    closeAllWindows: (hwnds) => ipcRenderer.invoke('close-all-windows', hwnds),
    getDesktopFiles: (directory) => ipcRenderer.invoke('get-desktop-files', directory),
    openDesktopFile: (filePath) => ipcRenderer.invoke('open-desktop-file', filePath),
    showItemInFolder: (filePath) => ipcRenderer.invoke('show-item-in-folder', filePath),
    createDesktopItem: (params) => ipcRenderer.invoke('create-desktop-item', params),
    deleteDesktopItem: (filePath) => ipcRenderer.invoke('delete-desktop-item', filePath),
    renameDesktopItem: (params) => ipcRenderer.invoke('rename-desktop-item', params),
    launchApp: (appId) => ipcRenderer.invoke('launch-app', appId),
    getCachedSnapshot: (appId) => ipcRenderer.invoke('get-cached-snapshot', appId),
    snapWindows: (layout) => ipcRenderer.invoke('snap-windows', layout),
    setSplitMode: (params) => ipcRenderer.invoke('set-split-mode', params),
    setWindowRect: (params) => ipcRenderer.invoke('set-window-rect', params),
    openWifiSettings: () => ipcRenderer.invoke('open-wifi-settings'),
    openBluetoothSettings: () => ipcRenderer.invoke('open-bluetooth-settings'),
    openSettings: (uri) => ipcRenderer.invoke('open-settings', uri),
    hideTaskbar: () => ipcRenderer.invoke('hide-taskbar'),
    showTaskbar: () => ipcRenderer.invoke('show-taskbar'),
    getStats: () => ipcRenderer.invoke('get-stats'),
    setWallpaper: (path) => ipcRenderer.invoke('set-wallpaper', path),
    exitShell: () => ipcRenderer.invoke('exit-shell'),
    openWindowsTaskbar: () => ipcRenderer.invoke('open-windows-taskbar'),
    openTaskMgr: () => ipcRenderer.invoke('open-task-mgr'),
    setCpuMode: (mode, targetPid) => ipcRenderer.invoke('set-cpu-mode', { mode, targetPid }),
    setWindowForeground: (hwnd) => ipcRenderer.invoke('set-window-foreground', hwnd),
    lowerLauncher: () => ipcRenderer.invoke('lower-launcher'),
    raiseLauncher: () => ipcRenderer.invoke('raise-launcher'),
    onWindowMinimized: (cb) => ipcRenderer.on('event-window-minimized', (e, val) => cb(val)),
    onForegroundChanged: (cb) => ipcRenderer.on('event-foreground-changed', (e, val) => cb(val)),
    onWindowRectChanged: (cb) => ipcRenderer.on('event-window-rect-changed', (e, val) => cb(val)),
    onWindowDestroyed: (cb) => ipcRenderer.on('event-window-destroyed', (e, val) => cb(val)),
    onTriggerHome: (cb) => ipcRenderer.on('trigger-home', (e, val) => cb(val)),
    onLaunchTimeout: (cb) => ipcRenderer.on('launch-timeout', (e, val) => cb(val)),
    onTriggerSwitcher: (cb) => ipcRenderer.on('trigger-switcher', (e, val) => cb(val)),
    onTriggerSpotlight: (cb) => ipcRenderer.on('toggle-spotlight', (e, val) => cb(val)),
    onToggleSpotlight: (cb) => ipcRenderer.on('toggle-spotlight', (e, val) => cb(val)),
    onAppsUpdated: (cb) => ipcRenderer.on('apps-updated', (e, val) => cb(val)),
    onRamWarning: (cb) => ipcRenderer.on('ram-warning-notification', (e, val) => cb(val)),
    onRamClosedApp: (cb) => ipcRenderer.on('ram-closed-app-notification', (e, val) => cb(val)),
    onRamUpdate: (cb) => ipcRenderer.on('ram-update', (e, val) => cb(val)),
    onRamAlert: (cb) => ipcRenderer.on('ram-alert', (e, val) => cb(val))
});